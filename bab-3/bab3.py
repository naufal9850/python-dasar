# integer 
umur = 17
print(umur)  # <class 'int'>

# float
tinggi = 178.5
print(tinggi)  # <class 'float'>

# string
nama = "Naufal"
print(nama)  # <class 'str'>

# boolean
is_active = True
print(is_active)  # <class 'bool'>

# list
buah = ["apel", "jeruk", "mangga"]
print(buah)  # <class 'list'>

# tuple
warna = ("merah", "hijau", "biru")
print(warna)  # <class 'tuple'>

# dictionary
mahasiswa = {"nama": "hadi", "umur": 31, "jurusan": "TPM"}
print(mahasiswa)  # <class 'dict'>

# set
angka = {1, 2, 3, 3, 4}
print(angka)  # {1, 2, 3, 4}
print(angka)  # <class 'set'>

x = 10       # int
y = float(x) # konversi ke float
z = str(x)   # konversi ke string

print(y, type(y))  # 10.0 <class 'float'>
print(z, type(z))  # "10" <class 'str'>
